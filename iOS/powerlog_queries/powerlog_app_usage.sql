SELECT

    ROW_NUMBER() OVER ( ORDER BY PLAPPTIMESERVICE_AGGREGATE_APPRUNTIME.timestamp ) AS "RowNumber",

    PLAPPTIMESERVICE_AGGREGATE_APPRUNTIME.BundleID AS "BundleID",
    PLAPPTIMESERVICE_AGGREGATE_APPRUNTIME.ScreenOnTime AS "ScreenOnTimeSeconds",
    PLAPPTIMESERVICE_AGGREGATE_APPRUNTIME.BackgroundTime AS "BackgroundTimeSeconds",

    strftime (
        '%F_%H:%M:%f',
        PLAPPTIMESERVICE_AGGREGATE_APPRUNTIME.timestamp,
        'unixepoch'
    ) AS "TimestampUtc",

    /* Source for each line of data */
    'Table: PLAPPTIMESERVICE_AGGREGATE_APPRUNTIME(ID: ' || PLAPPTIMESERVICE_AGGREGATE_APPRUNTIME.ID || ')' AS "DataSource"


FROM PLAPPTIMESERVICE_AGGREGATE_APPRUNTIME


WHERE
    PLAPPTIMESERVICE_AGGREGATE_APPRUNTIME.BundleID LIKE '%whatsapp%'


ORDER BY
    PLAPPTIMESERVICE_AGGREGATE_APPRUNTIME.timestamp ASC
