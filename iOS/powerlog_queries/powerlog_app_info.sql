[DATABASE]
    CurrentPowerlog.PLSQL
[NOTES]
    Get a listing of applications and associated data (app name, executable name,
    bundle ID, app version, app type and deletion date/status).
*/


SELECT

    ROW_NUMBER() OVER ( ORDER BY PLAPPLICATIONAGENT_EVENTNONE_ALLAPPS.APPDELETEDDATE ) AS RowNumber,

    strftime (
        '%F_%H:%M:%f',
        PLAPPLICATIONAGENT_EVENTNONE_ALLAPPS.TIMESTAMP,
        'unixepoch'
    ) AS "Timestamp",

    CASE PLAPPLICATIONAGENT_EVENTNONE_ALLAPPS.APPDELETEDDATE
        WHEN 0 THEN 'NotDeleted'
        ELSE strftime (
            '%F_%H:%M:%f',
            PLAPPLICATIONAGENT_EVENTNONE_ALLAPPS.APPDELETEDDATE,
            'unixepoch'
        )
    END AppDeleteDate,

    PLAPPLICATIONAGENT_EVENTNONE_ALLAPPS.APPNAME AS AppName,
    PLAPPLICATIONAGENT_EVENTNONE_ALLAPPS.APPEXECUTABLE AS AppExecutableName,
    PLAPPLICATIONAGENT_EVENTNONE_ALLAPPS.APPBUNDLEID AS BundleId,
    PLAPPLICATIONAGENT_EVENTNONE_ALLAPPS.APPBUILDVERSION AS AppBuildVersion,
    PLAPPLICATIONAGENT_EVENTNONE_ALLAPPS.APPBUNDLEVERSION AS AppBundleVersion,

    CASE PLAPPLICATIONAGENT_EVENTNONE_ALLAPPS.APPTYPE
        WHEN 1 THEN 'Background iOS Service'
        WHEN 3 THEN 'iOS Native App'
        WHEN 4 THEN '3rd Party Apps'
        ELSE 'Type ' || PLAPPLICATIONAGENT_EVENTNONE_ALLAPPS.APPTYPE
    END AS AppType,

    PLAPPLICATIONAGENT_EVENTNONE_ALLAPPS.ID AS PLApplicationAgentEventNoteAllAppsTableId


FROM
    PLAPPLICATIONAGENT_EVENTNONE_ALLAPPS
