SELECT

    ROW_NUMBER() OVER() AS 'RowNumber',
    ZRTVEHICLEEVENTHISTORYMO.Z_PK AS 'ZPk',

    datetime(ZRTVEHICLEEVENTHISTORYMO.ZDATE + 978307200, 'UNIXEPOCH') AS 'DateTimeUtc',
    datetime(ZRTVEHICLEEVENTHISTORYMO.ZLOCDATE + 978307200, 'UNIXEPOCH') AS 'LocationDateTimeUtc',

    ZRTVEHICLEEVENTHISTORYMO.ZLOCLATITUDE AS 'Latitude',
    ZRTVEHICLEEVENTHISTORYMO.ZLOCLONGITUDE AS 'Longitude',
    RTRIM(LTRIM(CONCAT(ROUND(ZRTVEHICLEEVENTHISTORYMO.ZLOCLATITUDE, 6), ',', ROUND(ZRTVEHICLEEVENTHISTORYMO.ZLOCLONGITUDE, 6)))) AS 'LatLong(Merged)',

    ZRTVEHICLEEVENTHISTORYMO.ZLOCUNCERTAINTY AS 'LocUncertainty',
    ZRTVEHICLEEVENTHISTORYMO.ZIDENTIFIER AS 'Identifier',


FROM ZRTVEHICLEEVENTHISTORYMO


ORDER BY ZRTVEHICLEEVENTHISTORYMO.ZDATE ASC