SELECT

    ROW_NUMBER() OVER ( ORDER BY ZRTVEHICLEEVENTMO.ZDATE ) AS RowNumber,

    ZRTVEHICLEEVENTMO.Z_PK AS ZPk,

    strftime ( '%F_%H:%M:%f', ZRTVEHICLEEVENTMO.ZDATE + 978307200, 'unixepoch' ) AS DateUtc,
    strftime ( '%F_%H:%M:%f', ZRTVEHICLEEVENTMO.ZLOCDATE + 978307200, 'unixepoch' ) AS LocationDateUtc,

    ZRTVEHICLEEVENTMO.ZLOCLATITUDE AS Latitude,
    ZRTVEHICLEEVENTMO.ZLOCLONGITUDE AS Longitude,

    RTRIM (
        LTRIM (
            CONCAT (
                ROUND ( ZRTVEHICLEEVENTMO.ZLOCLATITUDE, 6 ),
                ',',
                ROUND ( ZRTVEHICLEEVENTMO.ZLOCLONGITUDE, 6 )
            )
        )
    ) AS LatLongMerged,

    ZRTVEHICLEEVENTMO.ZVEHICLEIDENTIFIER AS VehicleIdentifier,
    ZRTVEHICLEEVENTMO.ZLOCUNCERTAINTY AS LocationUncertainty,
    ZRTVEHICLEEVENTMO.ZIDENTIFIER AS Identifier,
    ZRTVEHICLEEVENTMO.ZLOCATIONQUALITY AS LocationQuality,
    ZRTVEHICLEEVENTMO.ZUSERSETLOCATION AS UserSetLocation,
    ZRTVEHICLEEVENTMO.ZUSUALLOCATION AS UsualLocation,
    ZRTVEHICLEEVENTMO.ZNOTES AS Notes,
    ZRTVEHICLEEVENTMO.ZPHOTODATA AS PhotoData,

    /* Source for each line of data */
    'Table: ZRTVEHICLEEVENTMO(Z_PK: ' || ZRTVEHICLEEVENTMO.Z_PK || ')' AS DataSource


FROM ZRTVEHICLEEVENTMO


ORDER BY ZRTVEHICLEEVENTMO.ZDATE ASC
