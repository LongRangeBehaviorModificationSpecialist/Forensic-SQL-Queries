SELECT

    ZRTLEARNEDLOCATIONOFINTERESTTRANSITIONMO.Z_PK AS "LearnedLocationOfInterestTransitionMoZPk",

    vo.ZLOCATIONLATITUDE || ', ' || vo.ZLOCATIONLONGITUDE AS "OriginLocation",
    vd.ZLOCATIONLATITUDE || ', ' || vd.ZLOCATIONLONGITUDE AS "DestinationLocation",

    strftime ( '%F_%H:%M:%f', ZRTLEARNEDLOCATIONOFINTERESTTRANSITIONMO.ZSTARTDATE + 978307200, 'unixepoch' ) AS "StartDateTimeUtc",
    strftime ( '%F_%H:%M:%f', ZRTLEARNEDLOCATIONOFINTERESTTRANSITIONMO.ZSTOPDATE + 978307200, 'unixepoch' ) AS "StopDateTimeUtc",
    strftime ( '%F_%H:%M:%f', ZRTLEARNEDLOCATIONOFINTERESTTRANSITIONMO.ZCREATIONDATE + 978307200, 'unixepoch' ) AS "CreationDateTimeUtc",

    vo.Z_PK AS "OriginRecordZPk",
    vd.Z_PK AS "DestinationRecordZPk",

    vo.ZLOCATIONOFINTEREST AS "OriginLocationOfInterestId",
    vd.ZLOCATIONOFINTEREST AS "DestinationLocationOfInterestId",

    vo.ZDATAPOINTCOUNT AS "OriginDataPointCount",
    vd.ZDATAPOINTCOUNT AS "DestinationDataPointCount",

    hex ( ZRTLEARNEDLOCATIONOFINTERESTTRANSITIONMO.ZVISITIDENTIFIERORIGIN ) AS "OriginIdentifierHex",
    hex ( ZRTLEARNEDLOCATIONOFINTERESTTRANSITIONMO.ZVISITIDENTIFIERDESTINATION ) AS "DestinationIdentifierHex",

    /* Source for each line of data */
    'Local.sqlite; Table: ZRTLEARNEDLOCATIONOFINTERESTTRANSITIONMO(Z_PK:' || ZRTLEARNEDLOCATIONOFINTERESTTRANSITIONMO.Z_PK || '), ZRTLEARNEDLOCATIONOFINTERESTVISITMO(P_PK:' || vo.Z_PK || '), ZRTLEARNEDLOCATIONOFINTERESTVISITMO(P_PK:' || vd.Z_PK || ')' AS "DataSource"


FROM ZRTLEARNEDLOCATIONOFINTERESTTRANSITIONMO
    LEFT JOIN ZRTLEARNEDLOCATIONOFINTERESTVISITMO vo ON vo.ZIDENTIFIER = ZRTLEARNEDLOCATIONOFINTERESTTRANSITIONMO.ZVISITIDENTIFIERORIGIN
    LEFT JOIN ZRTLEARNEDLOCATIONOFINTERESTVISITMO vd ON vd.ZIDENTIFIER = ZRTLEARNEDLOCATIONOFINTERESTTRANSITIONMO.ZVISITIDENTIFIERDESTINATION


-- WHERE
--     ZRTLEARNEDLOCATIONOFINTERESTTRANSITIONMO.Z_PK IS '159459' OR
--     ZRTLEARNEDLOCATIONOFINTERESTTRANSITIONMO.Z_PK IS '159035' OR
--     ZRTLEARNEDLOCATIONOFINTERESTTRANSITIONMO.Z_PK IS '159341'


ORDER BY ZRTLEARNEDLOCATIONOFINTERESTTRANSITIONMO.ZSTARTDATE ASC
