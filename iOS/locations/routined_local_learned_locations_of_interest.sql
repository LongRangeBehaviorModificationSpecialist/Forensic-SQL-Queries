SELECT

    ROW_NUMBER() OVER() AS 'RowNumber',
    ZRTLEARNEDLOCATIONOFINTERESTVISITMO.Z_PK AS 'ZPk',
    ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZLOCATIONOFINTEREST AS 'LocationOfInterest',

    datetime(ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZENTRYDATE + 978307200, 'unixepoch') AS 'EntryDateTimeUtc',
    datetime(ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZEXITDATE + 978307200, 'unixepoch') AS 'ExitDateTimeUtc',

    (ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZEXITDATE-ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZENTRYDATE) / 60.00 AS 'ExitTime(Minutes)',

    ZRTLEARNEDLOCATIONOFINTERESTMO.ZLOCATIONLATITUDE AS 'Latitude',
    ZRTLEARNEDLOCATIONOFINTERESTMO.ZLOCATIONLONGITUDE AS 'Longitude',
    RTRIM(LTRIM(CONCAT(ROUND(ZRTLEARNEDLOCATIONOFINTERESTMO.ZLOCATIONLATITUDE, 6), ',', ROUND(ZRTLEARNEDLOCATIONOFINTERESTMO.ZLOCATIONLONGITUDE, 6)))) AS 'LatLong(Merged)',

    ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZCONFIDENCE AS 'Confidence',
    ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZLOCATIONOFINTERESTCONFIDENCE AS 'LOIConfidencde',
    ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZLOCATIONHORIZONTALUNCERTAINTY AS 'HorizonalLocationUncertainty',
    ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZLOCATIONVERTICALUNCERTAINTY AS 'VerticalLocationUncertainty',
    ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZDATAPOINTCOUNT AS 'DataPointCount',

    datetime(ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZCREATIONDATE + 978307200, 'unixepoch') AS 'PlaceCreationDateTimeUtc',
    datetime(ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZEXPIRATIONDATE + 978307200, 'unixepoch') AS 'ExpirationDateTimeUtc',

    ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZLOCATIONLATITUDE AS 'VisitLatitude',
    ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZLOCATIONLONGITUDE AS 'VisitLongitude',
    RTRIM(LTRIM(CONCAT(ROUND(ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZLOCATIONLATITUDE, 6), ',', ROUND(ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZLOCATIONLONGITUDE, 6)))) AS 'VisitLatLongMerged',

    /* Source for each line of data */
    'Local.sqlite; Table: ZRTLEARNEDLOCATIONOFINTERESTVISITMO(Z_PK:' || ZRTLEARNEDLOCATIONOFINTERESTVISITMO.Z_PK || ')' AS 'DataSource'


FROM ZRTLEARNEDLOCATIONOFINTERESTVISITMO
    LEFT JOIN ZRTLEARNEDLOCATIONOFINTERESTMO ON ZRTLEARNEDLOCATIONOFINTERESTMO.Z_PK = ZRTLEARNEDLOCATIONOFINTERESTVISITMO.ZLOCATIONOFINTEREST


ORDER BY ZRTLEARNEDLOCATIONOFINTERESTVISITMO.Z_PK ASC