SELECT

    ROW_NUMBER() OVER() AS 'RowNumber',
    ZRTADDRESSMO.Z_PK AS 'ZRTADDRESSMO.ZPk',
    ZRTMAPITEMMO.Z_PK AS 'ZRTMAPITEMMO.ZPk',
    ZRTADDRESSMO.ZMAPITEM AS 'ZRTDDRESSMO.ZMapItem',
    ZRTMAPITEMMO.ZADDRESS AS 'ZRTMAPITEMMO.ZAddress',

    strftime('%Y-%m-%dT%H:%M:%SZ', datetime(ZRTADDRESSMO.ZCREATIONDATE + 978307200, 'unixepoch')) AS 'ZRTADDRESSMO.CreationDateUtc',
    strftime('%Y-%m-%dT%H:%M:%SZ', datetime(ZRTADDRESSMO.ZEXPIRATIONDATE + 978307200, 'unixepoch')) AS 'ZRTADDRESSMO.ExpirationDateUtc',

    ZRTADDRESSMO.ZSUBTHOROUGHFARE || ' ' || ZRTADDRESSMO.ZTHOROUGHFARE || ', ' || ZRTADDRESSMO.ZLOCALITY || ', ' || ZRTADDRESSMO.ZADMINISTRATIVEAREA || ' ' || ZRTADDRESSMO.ZPOSTALCODE || ' ' || ZRTADDRESSMO.ZCOUNTRYCODE AS 'ZRTADDRESSMO.ItemAddress',

    ZRTMAPITEMMO.ZLATITUDE AS 'Latitude',
    ZRTMAPITEMMO.ZLONGITUDE AS 'Longitude',
    RTRIM(LTRIM(CONCAT(ROUND(ZRTMAPITEMMO.ZLATITUDE, 6), ',', ROUND(ZRTMAPITEMMO.ZLONGITUDE, 6)))) AS 'LatLongMerged',

    ZRTMAPITEMMO.ZUNCERTAINTY AS 'Uncertainty',

    /* Source for each line of data */
    'Cloud-V2.sqlite; Table: ZRTADDRESSMO(Z_PK:' || ZRTADDRESSMO.Z_PK || ')' AS 'DataSource'


FROM ZRTADDRESSMO
    LEFT JOIN ZRTMAPITEMMO ON ZRTADDRESSMO.ZMAPITEM = ZRTMAPITEMMO.ZADDRESS


ORDER BY
    ZRTADDRESSMO.ZCREATIONDATE DESC