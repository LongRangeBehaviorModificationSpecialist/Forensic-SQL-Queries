SELECT

    ROW_NUMBER() OVER() AS 'RowNumber',
    ZRTWIFIACCESSPOINTMO.Z_PK AS 'ZPk',

    strftime('%Y-%m-%dT%H:%M:%SZ', datetime(ZRTWIFIACCESSPOINTMO.ZDATE + 978307200, 'unixepoch')) AS 'DateUtc',

    ZRTWIFIACCESSPOINTMO.ZCHANNEL AS 'Channel',
    ZRTWIFIACCESSPOINTMO.ZRSSI AS 'Rssi',
    UPPER(ZRTWIFIACCESSPOINTMO.ZMAC) AS 'Mac'


FROM ZRTWIFIACCESSPOINTMO


ORDER BY
    ZRTWIFIACCESSPOINTMO.ZDATE ASC